  private void setRecipeEager(org.tura.model.designer.repository.serialized.recipe.Recipe recipe) {
    String session = UUID.randomUUID().toString();
    Boolean saveAttached = false;
    try {
      ProxyCommadStackProvider localStackProvider = getLocalStackProvider(session);
      if (recipe != null) {
        saveAttached = ((ObjectControl) recipe).getAttached();
        ((ObjectControl) recipe).setAttached(this.getAttached());
      }
      if (this.getRecipeEager() != null) {
        RemoveContainmentObjectOperation command = rmRecipe(this, this.getRecipeEager());
        command.setStackProvider(localStackProvider);
        command.prepare();
      }
      if (recipe != null) {
        AddContainmentObjectOperation command2 = addRecipe(this, recipe);
        command2.setStackProvider(localStackProvider);
        command2.prepare();
      }
      List<Object> changes = localStackProvider.get().getListOfCommand();
      if (changes.size() != 0) {
        localStackProvider.get().commit();
        if (this.getAttached() != null && this.getAttached()) {
          repository.getStackProvider().get().addCommands(changes);
        }
      }
    } catch (Exception e) {
      if (recipe != null) {
        ((ObjectControl) recipe).setAttached(saveAttached);
      }
      throw new RuntimeException(e);
    } finally {
      removeLocalStackProvider(session);
    }
  }

