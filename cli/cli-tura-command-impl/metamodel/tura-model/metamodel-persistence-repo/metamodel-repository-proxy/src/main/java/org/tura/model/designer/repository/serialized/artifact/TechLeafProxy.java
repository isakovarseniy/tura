  @Override
  public void setAttached(Boolean attachment) {
    String session = UUID.randomUUID().toString();
    try {
      ProxyCommadStackProvider localStackProvider = getLocalStackProvider(session);
      UpdateObjectOperation command =
          upd(
              this,
              localStackProvider,
              "attached",
              this.getObject().getAttached(),
              attachment,
              Boolean.class);
      if (command.prepare()) {
        localStackProvider.get().commit();
      }
      for (GenerationHint t : this.getHintsEager()) {
        ((ObjectControl) t).setAttached(true);
      }
      for (ConfigVariable t : this.getConfigVariablesEager()) {
        ((ObjectControl) t).setAttached(true);
      }
      for (ConfigHash t : this.getConfigHashesEager()) {
        ((ObjectControl) t).setAttached(true);
      }
      for (TechLeaf t : this.getTechLeafsEager()) {
        ((ObjectControl) t).setAttached(true);
      }
    } catch (Exception e) {
      throw new RuntimeException(e);
    } finally {
      removeLocalStackProvider(session);
    }
  }

